// The Go backend. It writes the canonical form of gofmt itself (T25.1): tabs, one statement per line, a blank line
// between top-level declarations, the fields of a struct aligned in columns and the imports sorted by path, and it
// writes only the helpers, imports and types that the program uses (definitions of backend-support.mjs). A function
// literal in an expression starts on the line of its expression and indents its body one level deeper than that line;
// every function here returns code whose first line starts at level 0, and `tabs` places it at its level.
import { readFileSync } from 'node:fs';
import {
  baseTarget, definition, definitionDataName, emitExpression, emitNodes, exportedName,
  fieldName, functionName, goString, goType, inputName,
} from '../backend-support.mjs';

export const language = 'go';

// The header of generated Go, by the convention that Go tools honor (`go help generate`).
export const GO_HEADER = '// Code generated by @polyspec/template-compiler. DO NOT EDIT.';

/**
 * The Go that the program holds as it is, from `<file>.go` in backends/go, where gofmt and go vet check it (make
 * lint-go-format, make test-go-backend-vet): the declarations after its package clause and imports, which
 * emitDeclarations writes for the whole program, without the final newline of the file.
 */
function goSource(file) {
  const text = readFileSync(new URL(`./go/${file}.go`, import.meta.url), 'utf8');
  return text.slice(text.search(/^(?:func|type) /m), -1);
}

const goSpan = span => `ast.Span{${span.join(', ')}}`;
const goLines = lines => `errs.LineIndex{${lines.join(', ')}}`;
const goResult = node => goType(node.valueType.source);
// An operand of a non-optional type where the result is optional: the optional type is a pointer in Go.
const goOperand = (expression, operand, node) => goType(node.valueType.source).startsWith('*') && !goType(operand.valueType.source).startsWith('*') ? `generatedPointer(${expression})` : expression;

/** `code` at `level`: every line that is not empty starts with `level` tabs. */
const tabs = (level, code) => code.split('\n').map(line => line === '' ? '' : '\t'.repeat(level) + line).join('\n');
/** The lines of a statement list, without the empty parts. */
const lines = (...parts) => parts.flat().filter(part => part !== '').join('\n');
/** A block `{ ... }` after `head`, with its statements one level deeper. */
const braced = (head, ...body) => `${head} {\n${tabs(1, lines(...body))}\n}`;
/** A function literal that is called at once, with its statements one level deeper. */
const called = (signature, ...body) => `${braced(signature, ...body)}()`;

/**
 * A struct type with its fields aligned as gofmt aligns them: the cells of a column are padded to the widest cell of
 * the column, and the last cell of a field is not padded.
 */
function goStruct(name, rows) {
  if (rows.length === 0) return `type ${name} struct{}`;
  const columns = Math.max(...rows.map(row => row.length));
  const widths = Array.from({ length: columns - 1 }, (_, column) => Math.max(...rows.filter(row => row.length > column + 1).map(row => row[column].length)));
  const field = row => row.map((cell, column) => column < row.length - 1 ? cell.padEnd(widths[column]) : cell).join(' ');
  return `type ${name} struct {\n${rows.map(row => `\t${field(row)}`).join('\n')}\n}`;
}

export function createTarget({ program }) {
  const target = baseTarget(language);
  target.var = (name, type, node) => program.dynamicRoot ? node.scope ? `generatedResult[${goType(type)}](scope.Lookup(frame, ${goString(name)}))` : `generatedMember[${goType(type)}](runtime, rootData, ${goString(name)}, frame, ${goSpan(node.span)})` : `assign.${exportedName(name)}`;
  target.local = (name, type) => `generatedResult[${goType(type)}](scope.Lookup(frame, ${goString(name)}))`;
  target.set = (name, value, level) => tabs(level, `scope.Locals[${goString(name)}] = generatedValue(${value})`);
  target.member = (object, key, owner, node) => owner.kind === 'any' ? `generatedMember[${goResult(node)}](runtime, ${object}, ${goString(key)}, frame, ${goSpan(node.span)})` : `${object}.${exportedName(key)}`;
  target.text = (value, level, node) => tabs(level, `generatedWrite(context, ${goString(value)}, frame, ${goSpan(node.span)})`);
  target.echo = (expression, level, node) => tabs(level, `generatedWrite(context, generatedEscape(runtime, ${expression}, frame, ${goSpan(node.expr.span)}), frame, ${goSpan(node.span)})`);
  const undefinedBlock = node => `panic(runtime.Error(frame, ${goSpan(node.span)}, errs.RuntimeBlockUndefined, ${goString(`define ${node.id} is not registered`)}))`;
  const enterBlock = (node, call) => [
    'blockScope := render.NewScope()',
    `generatedEnter(context, ${goString(node.target)}, frame, ${goSpan(node.span)})`,
    called('func()', 'defer context.Leave()', call),
  ];
  target.block = (node, n) => {
    if (node.target === null) {
      return tabs(n, braced('',
        `definition := definitions.${exportedName(node.id)}`,
        braced('if definition == nil || definition.HTML == nil', undefinedBlock(node)),
        `generatedWrite(context, *definition.HTML, frame, ${goSpan(node.span)})`).slice(1));
    }
    const defaults = node.inputs.filter(item => item.root).map(item => `${exportedName(item.name)}: ${emitExpression(item.root, target)}`).join(', ');
    const defined = node.inputs.map(item => braced(`if definition.Data.${exportedName(item.name)} != nil`, `input.${exportedName(item.name)} = *definition.Data.${exportedName(item.name)}`));
    const scoped = node.inputs.filter(item => item.scope).map(item => `input.${exportedName(item.name)} = ${emitExpression(item.scope, target)}`);
    const call = `${functionName(node.target)}(assign, definitions, input, context, runtime, rootData, blockScope)`;
    const input = `input := ${inputName(node.target)}{${defaults}}`;
    if (node.id === null) return tabs(n, braced('', input, scoped, enterBlock(node, call)).slice(1));
    const field = exportedName(node.id);
    const registryData = node.definition.template ? definitionDataName(node.definition.template) : 'struct{}';
    const registration = node.path === null
      ? braced('if definition == nil', undefinedBlock(node))
      : `${braced('if definition == nil', `definition = &Definition[${registryData}]{Template: ${goString(node.target)}}`, `definitions.${field} = definition`)} else ${braced(`if definition.HTML != nil || definition.Template != ${goString(node.target)}`, `panic(runtime.Error(frame, ${goSpan(node.span)}, errs.RuntimeBlockRedefined, ${goString(`define ${node.id} is registered with a different template`)}))`)}`;
    return tabs(n, braced('',
      `definition := definitions.${field}`,
      registration,
      `${braced('if definition != nil && definition.HTML != nil', `generatedWrite(context, *definition.HTML, frame, ${goSpan(node.span)})`)} else ${braced('',
        input,
        defined.length > 0 ? braced('if definition != nil && definition.Data != nil', defined) : '',
        scoped,
        enterBlock(node, call)).slice(1)}`).slice(1));
  };
  target.ifBlock = (node, n) => {
    const body = emitNodes(node.body, target, 0);
    const otherwise = node.otherwise ? emitNodes(node.otherwise, target, 0) : null;
    return tabs(n, `${braced(`if definitions.${exportedName(node.id)} != nil`, body)}${otherwise === null ? '' : ` else ${braced('', otherwise).slice(1)}`}`);
  };
  target.loopMeta = (loop, field) => `generatedLoopMeta(scope, ${goString(loop)}).${exportedName(field.replace(/_$/, ''))}`;
  target.toValue = value => `generatedValue(${value})`;
  target.index = (object, index, _owner, node) => `generatedIndex[${goResult(node)}](runtime, ${object}, ${index}, frame, ${goSpan(node.span)})`;
  const values = args => `[]value.Value{${args.map(item => `generatedValue(${item})`).join(', ')}}`;
  target.memberCall = (object, method, args, node) => `generatedMemberCall[${goResult(node)}](runtime, generatedValue(${object}), ${goString(method)}, ${values(args)}, frame, ${goSpan(node.span)})`;
  target.classCall = (className, method, args, node) => `generatedClassCall[${goResult(node)}](runtime, ${goString(className)}, ${goString(method)}, ${values(args)}, frame, ${goSpan(node.span)})`;
  target.call = (name, args, node) => `generatedCall[${goResult(node)}](runtime, ${goString(name)}, ${values(args)}, frame, ${goSpan(node.span)})`;
  target.unary = (operator, operand, node) => `generatedUnary[${goResult(node)}](runtime, ${goString(operator)}, ${operand}, frame, ${goSpan(node.span)})`;
  target.binary = (operator, left, right, node) => {
    if (operator === '&&') return called('func() bool', `left := ${left}`, braced('if !generatedTruthy(runtime, left)', 'return false'), `return generatedTruthy(runtime, ${right})`);
    if (operator === '||') return called('func() bool', `left := ${left}`, braced('if generatedTruthy(runtime, left)', 'return true'), `return generatedTruthy(runtime, ${right})`);
    // `??` returns the left operand when it is not null: a pointer of an optional type is read through after the test.
    if (operator === '??') {
      const left_ = goType(node.left.valueType.source).startsWith('*') && !goResult(node).startsWith('*') ? '*left' : goOperand('left', node.left, node);
      return called(`func() ${goResult(node)}`, `left := ${left}`, braced('if generatedValue(left) != nil', `return ${left_}`), `return ${goOperand(right, node.right, node)}`);
    }
    return `generatedBinary[${goResult(node)}](runtime, ${goString(operator)}, ${left}, ${right}, frame, ${goSpan(node.span)})`;
  };
  target.ternary = (test, thenValue, elseValue, node) => called(`func() ${goResult(node)}`, braced(`if generatedTruthy(runtime, ${test})`, `return ${goOperand(thenValue, node.consequent, node)}`), `return ${goOperand(elseValue, node.otherwise, node)}`);
  target.list = (items, type, node) => `generatedDepth(runtime, ${called(`func() ${goType(type.source)}`,
    `result := ${goType(type.source)}{}`,
    items.map(item => item.spread ? `result = append(result, generatedListSpread[${goType(type.item.source)}](runtime, ${item.value}, frame, ${goSpan(item.span)})...)` : `result = append(result, ${item.value})`),
    'return result')}, frame, ${goSpan(node.span)})`;
  target.map = (entries, type, node) => `generatedDepth(runtime, ${called(`func() ${goType(type.source)}`,
    `result := NewOrderedMap[${goType(type.key.source)}, ${goType(type.value.source)}]()`,
    entries.map(item => item.spread ? braced(`for _, entry := range generatedMapSpread[${goType(type.key.source)}, ${goType(type.value.source)}](runtime, ${item.value}, frame, ${goSpan(item.span)}).Entries()`, 'result.Set(entry.Key, entry.Value)') : `result.Set(${item.value[0]}, ${item.value[1]})`),
    'return result')}, frame, ${goSpan(node.span)})`;
  target.ifNode = (node, n) => {
    const branches = node.branches.map(branch => braced(`if generatedTruthy(runtime, ${emitExpression(branch.test, target)})`, emitNodes(branch.body, target, 0)));
    const otherwise = node.otherwise ? ` else ${braced('', emitNodes(node.otherwise, target, 0)).slice(1)}` : '';
    return tabs(n, `${branches.join(' else ')}${otherwise}`);
  };
  target.forNode = (node, n) => {
    const name = fieldName(node.name);
    const loop = goString(node.name);
    return tabs(n, braced('',
      `entries := generatedEntries(runtime, ${emitExpression(node.iter, target)}, frame, ${goSpan(node.span)})`,
      'entriesSize := len(entries)',
      'lastIndex := entriesSize - 1',
      `previous, hadPrevious := scope.Locals[${loop}]`,
      braced(`for ${name}_index, entry := range entries`,
        `${name}_key, ${name}_value := entry.Key, entry.Value`,
        `scope.Locals[${loop}] = ${name}_value`,
        `scope.Loops[${loop}] = append(scope.Loops[${loop}], &render.LoopMeta{Index: ${name}_index, Key: ${name}_key, Value: ${name}_value, Size: entriesSize, First: ${name}_index == 0, Last: ${name}_index == lastIndex})`,
        'context.Iterations++',
        `generatedLimit(runtime, "iteration", context.Iterations, frame, ${goSpan(node.span)})`,
        emitNodes(node.body, target, 0),
        `scope.Loops[${loop}] = scope.Loops[${loop}][:len(scope.Loops[${loop}])-1]`),
      `${braced('if hadPrevious', `scope.Locals[${loop}] = previous`)} else ${braced('', `delete(scope.Locals, ${loop})`).slice(1)}`,
      node.empty ? braced('if entriesSize == 0', emitNodes(node.empty, target, 0)) : '').slice(1));
  };
  target.include = (node, n) => tabs(n, lines(
    `generatedEnter(context, ${goString(node.target)}, frame, ${goSpan(node.span)})`,
    called('func()', 'defer context.Leave()', `${functionName(node.target)}(assign, definitions, ${inputName(node.target)}{${node.inputs.map(item => `${exportedName(item.name)}: ${emitExpression(item.value, target)}`).join(', ')}}, context, runtime, rootData, scope)`)));
  return target;
}

const imports = [
  ['bytes', '"bytes"'], ['json', '"encoding/json"'], ['errors', '"errors"'], ['fmt', '"fmt"'],
  ['template', 'template "github.com/polyspec/template/packages/go"'],
  ['ast', '"github.com/polyspec/template/packages/go/ast"'], ['errs', '"github.com/polyspec/template/packages/go/errs"'],
  ['functions', '"github.com/polyspec/template/packages/go/functions"'], ['render', '"github.com/polyspec/template/packages/go/render"'],
  ['value', '"github.com/polyspec/template/packages/go/value"'], ['time', '"time"'], ['utf8', '"unicode/utf8"'],
];

export function emitDeclarations(context) {
  const { program, manifest, templateBodies } = context;
  const fields = manifest.fields ?? {};
  const records = { ...manifest.records, ...manifest.recordsExtra };
  const tag = name => `\`json:"${name}"\``;
  // A record reaches a runtime operation as a map of its declared fields in declaration order (VAL-21).
  const goRecords = Object.entries(records).flatMap(([name, members]) => [
    goStruct(name, Object.entries(members).map(([key, type]) => [exportedName(key), goType(type), tag(key)])),
    braced(`func (r ${name}) TemplateValue() value.Value`, 'result := value.NewOrderedMap()', Object.keys(members).map(key => `result.Set(${goString(key)}, generatedValue(r.${exportedName(key)}))`), 'return result'),
  ]);
  const inputTypes = templateBodies.map(template => goStruct(template.input, [...template.inputs].map(([name, type]) => [exportedName(name), goType(type.source), tag(name)])));
  const definitionDataTypes = templateBodies.map(template => goStruct(definitionDataName(template.name), [...template.inputs].map(([name, type]) => [exportedName(name), `*${goType(type.source)}`, tag(name)])));
  const definitionsType = goStruct('Definitions', [...program.definitions].map(([name, definition]) => [exportedName(name), `*Definition[${definition.template ? definitionDataName(definition.template) : 'struct{}'}]`, tag(name)]));
  const assignType = goStruct('Assign', program.dynamicRoot ? [] : Object.entries(fields).map(([name, type]) => [exportedName(name), goType(type), tag(name)]));
  return [
    `${GO_HEADER}\n\npackage generated\n\nimport (`,
    // An import is kept when the program uses its package.
    ...imports.map(([name, path]) => definition(name, `\t${path}`, new RegExp(`\\b${name}\\.`))),
    ')',
    ...[...goRecords, assignType, ...inputTypes, ...definitionDataTypes,
      goStruct('Definition[T any]', [['Template', 'string', tag('template')], ['HTML', '*string', tag('html')], ['Data', '*T', tag('data')]]),
      definitionsType,
      goStruct('ArtifactManifest', ['Schema int', 'Mode string', 'Target string', 'Entry string', 'SourceDigest string', 'TypeDigest string', 'ContractDigest string', 'Files map[string]string'].map(row => row.split(' ')))].map(code => `\n${code}`),
    definition('OrderedMap', `\n${goSource('ordered_map')}`,
    // The OrderedMap of the program, not value.OrderedMap of the runtime.
    /(?<![.\w])OrderedMap\b/),
  ];
}

// The helpers of the program in their order, each in `generated_<name>.go` and kept only when the program uses it.
const helpers = [
  'generatedPanic', 'generatedValue', 'generatedResult', 'generatedAs', 'generatedTruthy', 'generatedUnary', 'generatedBinary',
  'generatedMember', 'generatedIndex', 'generatedDepth', 'generatedMemberCall', 'generatedClassCall', 'generatedCall',
  'generatedEscape', 'generatedEntries', 'generatedListSpread', 'generatedMapSpread', 'generatedLoopMeta', 'generatedWrite',
  'generatedEnter', 'generatedLimit', 'generatedPointer', 'generatedPlain', 'generatedDecode', 'generatedEnv',
];

export function emitRuntime() {
  return helpers.map(name => definition(name, `\n${goSource(name.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`))}`));
}

export function emitTemplates(context) {
  return context.templateBodies.map(template => {
    const typed = context.program.templates.get(template.name);
    return `\n${braced(`func ${template.function}(assign Assign, definitions *Definitions, input ${template.input}, context *render.Context, runtime *render.RuntimeBindings, rootData *value.OrderedMap, scope *render.Scope)`,
      `frame := render.NewFrame(${goString(template.name)}, ${goLines(typed.lines)}, rootData)`,
      [...template.inputs].map(([name]) => `scope.Locals[${goString(name)}] = generatedValue(input.${exportedName(name)})`),
      // The statements of the body at level 0, which the function places one level deeper.
      emitNodes(typed.body, context.target, 0))}`;
  });
}

function definitionCase(context, id, definition) {
  const field = exportedName(id);
  const dataType = definition.template ? definitionDataName(definition.template) : 'struct{}';
  const inputs = definition.template ? [...context.program.templates.get(definition.template).inputs] : [];
  const fail = message => `return nil, nil, fmt.Errorf(${goString(message)}, id)`;
  const html = definition.html
    ? braced('if input.HTML != nil',
      braced('if input.Template != "" || input.Data != nil', fail('define.%s has an invalid html entry')),
      `definitions.${field} = &Definition[${dataType}]{HTML: input.HTML}`,
      'targets[id] = generatedTarget{html: input.HTML}',
      'continue')
    : braced('if input.HTML != nil', fail('define.%s has an invalid html entry'));
  // Definition data is bound as its own value and converted field by field, so a native object in an `any` field stays
  // the original value (VAL-18, VAL-20).
  const converted = inputs.map(([name, type]) => braced(`if raw, found := data.Get(${goString(name)}); found`,
    `converted, err := generatedAs[${goType(type.source)}](raw)`,
    braced('if err != nil', `return nil, nil, fmt.Errorf("define.%s.data.%s: %w", id, ${goString(name)}, err)`),
    `definitionData.${exportedName(name)} = &converted`));
  const notMap = 'return nil, nil, &value.BindError{Code: errs.DataUnsupportedType, Message: "define " + id + ": data is not a map"}';
  const data = braced('if input.Data != nil',
    'bound, err := value.BindData(input.Data)',
    braced('if err != nil', 'return nil, nil, err'),
    converted.length > 0 ? ['data, ok := bound.(*value.OrderedMap)', braced('if !ok', notMap)] : braced('if _, ok := bound.(*value.OrderedMap); !ok', notMap),
    `definitionData := ${dataType}{}`,
    converted,
    'entry.Data = &definitionData');
  return `case ${goString(id)}:\n${tabs(1, lines(
    html,
    braced(`if input.Template != ${goString(definition.template ?? '')}`, fail('define.%s has an invalid template')),
    `entry := &Definition[${dataType}]{Template: input.Template}`,
    data,
    `definitions.${field} = entry`,
    `targets[id] = generatedTarget{target: ${goString(definition.template ?? '')}}`))}`;
}

export function emitEntry(context) {
  const dispatch = context.templateBodies.filter(template => template.inputs.size === 0).map(template => `case ${goString(template.name)}:\n${tabs(1, `${template.function}(assign, definitions, ${template.input}{}, context, runtime, rootData, scope)\nreturn`)}`);
  const definitions = [...context.program.definitions];
  const cases = definitions.map(([id, definition]) => definitionCase(context, id, definition));
  const bindAssign = context.program.dynamicRoot ? '' : braced('if err := generatedDecode(rootData, &typedAssign); err != nil', 'return nil, err');
  const failure = message => `return "", ${message}`;
  return [
    `\n${braced('func renderTemplate(target string, assign Assign, definitions *Definitions, context *render.Context, runtime *render.RuntimeBindings, rootData *value.OrderedMap, scope *render.Scope)',
      `switch target {\n${lines(dispatch, 'default:', tabs(1, 'panic(context.Fail(errs.LoadNotFound, nil, nil, "template "+target+" does not exist"))'))}\n}`)}`,
    `\n${goStruct('generatedTarget', [['target', 'string'], ['html', '*string']])}`,
    `\n${braced('func generatedBindDefinitions(input map[string]template.DefineInput) (*Definitions, map[string]generatedTarget, error)',
      'definitions := &Definitions{}',
      'targets := map[string]generatedTarget{}',
      braced(definitions.length > 0 ? 'for id, input := range input' : 'for id := range input',
        braced('if !utf8.ValidString(id)', 'return nil, nil, &value.BindError{Code: errs.DataInvalidUTF8, Message: "a define id is not valid UTF-8"}'),
        `switch id {\n${lines(cases, 'default:', tabs(1, 'return nil, nil, fmt.Errorf("define.%s is not declared", id)'))}\n}`),
      'return definitions, targets, nil')}`,
    `\n${goStruct('GeneratedProgram', [['Runtime', '*template.RuntimeEnvironment']])}`,
    `\n${braced('func NewGeneratedProgram(options template.Options) (*GeneratedProgram, error)',
      'runtime, err := template.NewRuntimeEnvironment(options.Limits, options.Functions)',
      braced('if err != nil', 'return nil, err'),
      'return &GeneratedProgram{Runtime: runtime}, nil')}`,
    `\n${goStruct('generatedPrepared', [['name', 'string'], ['target', 'string'], ['assign', 'Assign'], ['definitions', '*Definitions'], ['rootData', '*value.OrderedMap'], ['env', 'functions.Env'], ['runtime', '*template.RuntimeEnvironment'], ['html', '*string']])}`,
    `\n${braced('func (p *generatedPrepared) Render() (string, error)', 'return render.Guard(p.name, p.render)')}`,
    `\n${braced('func (p *generatedPrepared) render() (string, error)',
      'context := render.NewContext(p.runtime, p.rootData, p.env, p.target)',
      'runtime := render.NewRuntimeBindings(context)',
      'scope := render.NewScope()',
      braced('if err := context.Enter(p.target, nil, nil); err != nil', failure('err')),
      'defer context.Leave()',
      `${braced('if p.html != nil', braced('if err := context.Write(*p.html, nil, nil); err != nil', failure('err')))} else ${braced('', 'renderTemplate(p.target, p.assign, p.definitions, context, runtime, p.rootData, scope)').slice(1)}`,
      'return context.Output(), nil')}`,
    `\n${braced('func (p *GeneratedProgram) Prepare(target any, assign any, options template.RenderOptions) (template.Prepared, error)',
      'name, ok := target.(string)',
      braced('if !ok', 'return nil, fmt.Errorf("generated target must be a template name")'),
      `return render.Guard(name, ${braced('func() (template.Prepared, error)', 'return p.prepare(name, assign, options)')})`)}`,
    `\n${braced('func generatedBindFailure(name string, err error) error',
      'var bindError *value.BindError',
      braced('if errors.As(err, &bindError)', 'return errs.WithoutPosition(bindError.Code, name, bindError.Message)'),
      'return err')}`,
    `\n${braced('func (p *GeneratedProgram) prepare(name string, assign any, options template.RenderOptions) (template.Prepared, error)',
      'rootData, err := value.BindMap(assign)',
      braced('if err != nil', 'return nil, generatedBindFailure(name, err)'),
      'var typedAssign Assign',
      bindAssign,
      'definitions, targets, err := generatedBindDefinitions(options.Define)',
      braced('if err != nil', 'return nil, generatedBindFailure(name, err)'),
      'resolved := targets[name]',
      'targetName := name',
      braced('if resolved.target != ""', 'targetName = resolved.target'),
      'return &generatedPrepared{name: name, target: targetName, assign: typedAssign, definitions: definitions, rootData: rootData, env: generatedEnv(options), runtime: p.Runtime, html: resolved.html}, nil')}`,
    `\n${braced('func (p *GeneratedProgram) Render(target any, assign any, options template.RenderOptions) (string, error)',
      'prepared, err := p.Prepare(target, assign, options)',
      braced('if err != nil', failure('err')),
      'return prepared.Render()')}`,
    '\nvar _ template.Program = (*GeneratedProgram)(nil)',
  ];
}
