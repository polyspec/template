#!/usr/bin/env node
// Lints the generated programs as the code of a consumer (T25.1): the committed showcase artifacts, which
// make artifact-digest-check holds to the compiler of the tree, are the generated fixture of each target. Each target
// passes the formatter and the unused-code lint of its ecosystem at the versions that this repository pins:
// - Go: the header of the Go convention for generated code, `gofmt -l` lists no file, and golangci-lint `unused` reports
//   nothing. golangci-lint skips a file with that header by default (exclusions.generated: lax), so this check runs it
//   with a configuration of its own that lints generated files.
// - Rust: clippy with -D warnings on a library crate whose public modules include the programs, so the public API of a
//   program is used and only what the program does not use is dead code.
// - TypeScript: oxlint `no-unused-vars`.
// - PHP: `pint --test --preset psr12` and phpcs with phpcs.xml.dist (PSR-12); the soft limit of 120 columns, which phpcs
//   reports as a warning, waits for T25.2.
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { checkLanguages } from './language-checks.mjs';
import { showcasePhpDirectory } from '../tools/showcase/php-namespace.mjs';
import { CARGO, root, rustWorkspace, temporaryDirectory } from './temporary-workspace.mjs';

export const GO_HEADER = '// Code generated by @polyspec/template-compiler. DO NOT EDIT.';

const adapters = join(root, 'tools/showcase/adapters');
const typed = join(adapters, 'generated/typed');
const scenarios = readdirSync(join(root, 'examples/site/scenarios'), { withFileTypes: true })
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name)
  .sort();
if (scenarios.length === 0) throw new Error('examples/site/scenarios holds no scenario');
const goFiles = scenarios.map(id => join(adapters, 'go/generated', id, 'generated.go'));
const typedFiles = extension => scenarios.map(id => join(typed, `${id}.${extension}`));

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: options.cwd ?? root, encoding: 'utf8', env: { ...process.env, ...options.env }, maxBuffer: 64 * 1024 * 1024 });
  if (result.error) throw result.error;
  if (result.status !== 0 || (options.quiet && result.stdout.trim() !== '')) {
    throw new Error(`${command} ${args.join(' ')} exited with ${result.status}\n${result.stdout}${result.stderr}`.trim());
  }
  return result.stdout;
}

function checkGo() {
  for (const file of goFiles) {
    const first = readFileSync(file, 'utf8').split('\n', 1)[0];
    if (first !== GO_HEADER) throw new Error(`${file}: the first line is ${JSON.stringify(first)}, not ${JSON.stringify(GO_HEADER)}`);
  }
  run('gofmt', ['-l', ...goFiles], { quiet: true });
  const directory = temporaryDirectory('generated-lint-go');
  try {
    const config = join(directory, 'golangci.yml');
    writeFileSync(config, 'version: "2"\nlinters:\n  default: none\n  enable:\n    - unused\n  exclusions:\n    generated: disable\n');
    run('golangci-lint', ['run', '--config', config, './generated/...'], { cwd: join(adapters, 'go') });
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function checkRust() {
  const crate = rustWorkspace('generated-lint-rust');
  try {
    const modules = scenarios.map(id => `pub mod ${id.replaceAll('-', '_')} {\n    include!(${JSON.stringify(join(typed, `${id}.rust`))});\n}\n`).join('');
    writeFileSync(join(crate.directory, 'src/lib.rs'), modules);
    run(CARGO, ['clippy', '--locked', '--offline', '--manifest-path', crate.manifest, '--lib', '--', '-D', 'warnings'], { env: { CARGO_TARGET_DIR: crate.targetDirectory } });
  } finally {
    rmSync(crate.directory, { recursive: true, force: true });
  }
}

function checkTypeScript() {
  run(resolve(root, 'node_modules/.bin/oxlint'), ['--allow', 'all', '--deny', 'no-unused-vars', ...typedFiles('ts')]);
}

function checkPhp() {
  // The PHP program of a scenario is a directory of PSR-4 files (T25.1).
  const files = scenarios.flatMap(id => readdirSync(join(root, showcasePhpDirectory(id))).map(name => join(root, showcasePhpDirectory(id), name)));
  run(join(root, 'packages/template-php/vendor/bin/pint'), ['--test', '--preset', 'psr12', ...files]);
  // T25.2: --warning-severity=0 hides the line length warnings of PSR-12 until the PHP emitter keeps lines within 120
  // columns; remove it then.
  run('phpcs', ['--standard=phpcs.xml.dist', '--warning-severity=0', ...files]);
}

checkLanguages('generated lint', { Go: checkGo, Rust: checkRust, TypeScript: checkTypeScript, PHP: checkPhp });
process.stdout.write(`generated lint: the Go, Rust, TypeScript and PHP programs of ${scenarios.length} scenarios pass\n`);
